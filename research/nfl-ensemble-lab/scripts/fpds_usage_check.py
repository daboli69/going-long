"""Test whether FantasyPoints metrics improve the simulated game's player numbers, and save the rule the simulation uses.

    .venv\\Scripts\\python.exe scripts\\fpds_usage_check.py

Fits on 2022-2024 and scores on 2025 and on 2026 so far (games the fit never saw), using only weeks before each game.
A blend is kept only if it passes the gate in lab/fpds_usage.py. Writes docs/FPDS_USAGE_CHECK.md and docs/fpds_usage_check.json
(aggregate numbers only, no FantasyPoints rows) and data/cache/fpds_usage_rule.json. Local files only; no network.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from lab import fpds_usage as X  # noqa: E402

NAMES = {"rec_yds": "Receiving yards", "rec": "Catches", "rush_yds": "Rushing yards"}
FEAT = {"tgt_pct": "target share", "rte_yprr": "routes x yards per route", "ay_share": "air yards share", "rte_pct": "routes run",
        "att_pct": "carry share", "snap_pct": "snap share", "base": "nflverse share"}


def mix(w: dict) -> str:
    return ", ".join(f"{v:.0%} {FEAT.get(k, k)}" for k, v in w.items() if v)


GROUPS = (("all", 6, "Everyone expected to play"), ("thin", 3, "Played 3 or fewer of last 6"))


def main():
    runs = {name: X.evaluate(hi_n=hi) for name, hi, _ in GROUPS}
    td = X.evaluate_td()
    # for each stat: everyone if that passes the gate, else players with thin history if that does, else nflverse only
    chosen = {}
    for stat in X.STAT_FEATURES:
        for name, hi, _ in GROUPS:
            passed = X.gate(runs[name]).get(stat)
            if passed:
                chosen[stat] = {"group": name, "max_n": hi, "mix": {k: round(v, 2) for k, v in passed.items()}}
                break
    td_rule = {}
    for kind, r in td["stats"].items():
        t5, t6 = r["test_2025"], r["test_2026"]
        uses = kind == "rec_td" and t5["diff_lo"] > 0 and t6["loglik_with_fpds"] >= t6["loglik_nflverse_only"]
        td_rule[kind] = {"uses_fpds": bool(uses), "weights": {k: round(v, 2) for k, v in (r["weights_all"] if uses else r["weights_nflverse_only"]).items()}}
    through = X.through()
    rule = {"created_at": pd.Timestamp.now(tz="UTC").isoformat(), "mode": "last6", "weights": chosen, "td": td_rule, "through": through,
            "evidence": {name: r["games"] for name, r in runs.items()}}
    X.RULE_PATH.parent.mkdir(parents=True, exist_ok=True)
    X.RULE_PATH.write_text(json.dumps(rule, indent=1), encoding="utf-8")
    (ROOT / "docs" / "fpds_usage_check.json").write_text(json.dumps({"volume": runs, "td": td, "rule": rule}, indent=1, default=str), encoding="utf-8")

    L = ["# FantasyPoints metrics in the simulated game: what was tested", "",
         "Generated by `scripts/fpds_usage_check.py`. Fitted on 2022 to 2024, scored on 2025 and on 2026 so far (weeks 3 to 7) using only weeks "
         "before each game. Aggregate numbers only; no FantasyPoints rows are published.", "",
         f"FantasyPoints weekly rows reach week {through['weekly_through']} of 2026. Receiving metrics for weeks 5 and 6 come from a partial export "
         "(about 15 players a week against about 230 in a normal week), so they are left out; weeks 1 to 4 and 7 are used.", "",
         "## Who gets the ball (catches, receiving yards, rushing yards)", "",
         "Error is the typical miss, in yards or catches, for one player in one game (root mean squared error). Lower is better. "
         "\"nflverse only\" is the share from each player's last six games, which is what the simulation used before.", "",
         "| Stat | Players | Year | nflverse only | With FantasyPoints | Difference, 90% interval | Used |", "|---|---|---|---|---|---|---|"]
    for stat in X.STAT_FEATURES:
        for name, hi, gname in GROUPS:
            r = runs[name]["stats"][stat]
            for k, label in (("test_2025", "2025"), ("test_2026", "2026")):
                t = r[k]["thin_history"]
                used = stat in chosen and chosen[stat]["group"] == name
                L.append(f"| {NAMES[stat]} | {gname} | {label} | {t['rmse_old']:.2f} | {t['rmse_new']:.2f} | {t['rmse_new'] - t['rmse_old']:+.2f} "
                         f"({t['diff_lo']:+.2f} to {t['diff_hi']:+.2f}) | {'yes' if used else 'no'} |")
    L += ["", "Blend weights, fitted on 2022 to 2024:", ""]
    for stat in X.STAT_FEATURES:
        if stat in chosen:
            c = chosen[stat]
            L.append(f"- {NAMES[stat]}: {mix(c['mix'])}, for {'everyone expected to play' if c['group'] == 'all' else 'players who played 3 or fewer of the last 6'}. Passed the gate and is used.")
        else:
            L.append(f"- {NAMES[stat]}: no blend passed the gate (both years must show a gain with the whole interval below zero), so the nflverse share is used.")
    L += ["", "The narrower group (thin history only) is used for a stat only when the broader group fails the gate, so it shows \"no\" when everyone already passed.",
          "", "Players outside the chosen group keep the nflverse share. Historical weeks were exported in 2026, so they are each week's final values rather than what was posted at the time; target and route counts rarely change, but this is a limit of the test.", "",
          "## Who catches touchdowns", "",
          "Score is the average log-likelihood of the player who actually caught each touchdown; higher is better.", "",
          "| Kind | Year | Games with a score | nflverse only | With FantasyPoints red-zone targets | Difference, 90% interval | Used |", "|---|---|---|---|---|---|---|"]
    for kind, r in td["stats"].items():
        for k, label in (("test_2025", "2025"), ("test_2026", "2026")):
            t = r[k]
            L.append(f"| {'Receiving' if kind == 'rec_td' else 'Rushing'} | {label} | {t['games_with_td']} | {t['loglik_nflverse_only']:.3f} | {t['loglik_with_fpds']:.3f} | "
                     f"{t['loglik_with_fpds'] - t['loglik_nflverse_only']:+.3f} ({t['diff_lo']:+.3f} to {t['diff_hi']:+.3f}) | {'yes' if td_rule[kind]['uses_fpds'] else 'no'} |")
    L += ["", "Receiving touchdown weights used: " + mix({k.replace('td_history', 'touchdown history').replace('yards', 'yardage share').replace('fpds', 'red-zone targets'): v
                                                         for k, v in td_rule['rec_td']['weights'].items()}) + ".",
          "Rushing touchdowns use yardage share and touchdown history only; goal-line carry share from FantasyPoints did not help.", "",
          "## Not tested, so not used", "",
          "- FantasyPoints stuff rate: it averages about 47% against about 17% for carries that gain 0 or fewer yards, so the definition differs. The data dictionary also calls header definitions unverified.",
          "- Pass-and-run tendencies by game state: nflverse play-by-play gives the same numbers, so FantasyPoints adds nothing new to test.",
          "- Rushing volume from carry share and snap share: no gain that held in both years.", ""]
    (ROOT / "docs" / "FPDS_USAGE_CHECK.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L[:30]))
    print("\nRULE:", json.dumps({k: rule[k] for k in ("weights", "td")}))


if __name__ == "__main__":
    main()
