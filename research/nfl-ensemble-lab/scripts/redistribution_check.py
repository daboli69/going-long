"""Test where a missing player's production goes, team by team, and save the rule the simulation uses.

    .venv\\Scripts\\python.exe scripts\\redistribution_check.py

Fits each rule on 2025 absences and scores it on 2026 games only (the method never sees the games it is scored on).
Writes docs/REDISTRIBUTION_CHECK.md and docs/redistribution_check.json, then refits the chosen rule on 2025 and 2026
together and saves it to data/cache/redistribution_rule.json. Local files only; no network.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from lab import usage as U  # noqa: E402

LABELS = {"rec_yds": "Receiving yards", "rec": "Catches", "rush_yds": "Rushing yards"}


def fmt(x, d=1):
    return "n/a" if x != x else f"{x:+.{d}f}" if d else f"{x:.0f}"


def main():
    r = U.evaluate((2025,), (2026,))
    rule = r["rule"]
    names = list(r["scores"])
    chosen, none, old = rule["name"], names[0], names[1]
    lines = ["# Where a missing player's production goes", "",
             f"Generated by `scripts/redistribution_check.py`. Fitted on {r['train_cases']} team-games from 2025 where a regular was ruled out "
             f"(official report Out or Doubtful), scored on {r['test_cases']} such team-games from 2026 that the fit never saw.", "",
             "## Rule used by the simulation", "",
             "| | Receiving yards | Catches | Rushing yards |", "|---|---|---|---|",
             "| Share the team keeps | " + " | ".join(f"{rule['k'][s]:.0%}" for s in U.STATS) + " |",
             "| Part of that going to his replacement | " + " | ".join(f"{rule['to_new'][s]:.0%}" for s in U.STATS) + " |", "",
             "The rest goes to the regulars in proportion to their share, weighted by position (weight above 1 means that position "
             "takes more than its usage alone suggests):", "",
             "| Missing | Receiving | Weight |", "|---|---|---|"]
    for key, v in sorted(rule["m"].items()):
        a, b = key.split("->")
        if a in ("WR", "TE", "RB", "QB") and b in ("WR", "TE", "RB", "QB"):
            lines.append(f"| {a} | {b} | {v:.2f} |")
    lines += ["", "## All rules on 2026 games", "",
              "Per-player error is the root mean squared error for each regular (yards or catches per game). Team total miss is the "
              "average of projected minus actual for the whole team; negative means the rule left production unaccounted for.", "",
              "| Rule | Stat | Per-player error | Team total miss | Team total miss, absolute | Replacement miss |", "|---|---|---|---|---|---|"]
    for n, sc in r["scores"].items():
        for s in U.STATS:
            v = sc[s]
            lines.append(f"| {n} | {LABELS[s]} | {v['rmse']:.2f} | {fmt(v['team_bias'])} | {v['team_abs']:.1f} | {fmt(v['replacement_bias'])} |")
    lines += ["", "## Team by team (2026 games)", "",
              "Team total miss in receiving and rushing yards per absence game: no redistribution against the rule used. "
              "The team's own kept share is shown for reference; it did not beat the league share on 2026 games, so the simulation uses the league share.", "",
              "| Team | 2025 absences | 2026 absences | Receiving miss, none | Receiving miss, rule | Rushing miss, none | Rushing miss, rule | Own kept share (rec / rush) |",
              "|---|---|---|---|---|---|---|---|"]
    for t, d in r["per_team"].items():
        sc = d["scores"]
        cell = lambda name, s: fmt(sc[name][s]["team_bias"]) if sc else "no 2026 absences"
        lines.append(f"| {t} | {d['train_cases']} | {d['test_cases']} | {cell(none, 'rec_yds')} | {cell(chosen, 'rec_yds')} | "
                     f"{cell(none, 'rush_yds')} | {cell(chosen, 'rush_yds')} | {d['team_k']['rec_yds']:.2f} / {d['team_k']['rush_yds']:.2f} |")
    teams = [d for d in r["per_team"].values() if d["scores"]]
    better = sum(1 for d in teams if abs(d["scores"][chosen]["rec_yds"]["team_bias"]) < abs(d["scores"][none]["rec_yds"]["team_bias"]))
    lines += ["", f"Receiving-yard team totals were closer with the rule than with no redistribution for {better} of {len(teams)} teams with 2026 absences. "
              "Per team the samples are small (often one to four games), so single teams can go either way.", ""]
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "REDISTRIBUTION_CHECK.md").write_text("\n".join(lines), encoding="utf-8")
    (ROOT / "docs" / "redistribution_check.json").write_text(json.dumps(r, indent=1, default=str), encoding="utf-8")

    final = U.fit(U._team_games((2025, 2026)))
    U.save_rule(final, [2025, 2026])
    print("\n".join(lines[:12]))
    print(f"\nSaved rule fitted on 2025-2026: k={final.k} to_new={ {k: round(v, 3) for k, v in final.to_new.items()} }")


if __name__ == "__main__":
    main()
