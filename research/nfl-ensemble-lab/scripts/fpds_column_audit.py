r"""Which FantasyPoints columns with 2026 data does the code never read? Metadata only: names, counts, and where each name appears in code.

    .venv\Scripts\python.exe scripts\fpds_column_audit.py

For every imported table (the `working_usable` file, 2021 to 2026) it lists each column with data in 2026 and sorts it into: read by the live
projection (lab/ outside the research folders), read only by research code, or read nowhere. A column counts as read when its full name, or its
last part together with its group, appears in a source file. Writes docs/FPDS_COLUMN_AUDIT.md and docs/fpds_column_audit.json.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from lab import fpds_usage as X  # noqa: E402

RESEARCH = ("fpds_research", "fpds_next", "fpds_ingest", "fpds_improve", "props", "fpds_manual")
IDENT = {"rank", "name", "team", "pos", "g", "player_id", "opp", "unit", "men", "role_s"}
META = re.compile(r"^(_|source_|pid|entity|game_id_asof|opponent_asof|team_details__(rank|name|pos|g)$|splits__)")


def sources():
    live, research = {}, {}
    for p in list((ROOT / "lab").rglob("*.py")) + list((ROOT / "scripts").glob("*.py")):
        txt = p.read_text(encoding="utf-8", errors="ignore").lower()
        rel = p.relative_to(ROOT).as_posix()
        (research if any(k in rel for k in RESEARCH) or rel.startswith("scripts/") and "fpds" in rel else live)[rel] = txt
    return live, research


def read_in(col: str, blob: dict) -> list[str]:
    group, _, leaf = col.partition("__")
    pats = [col.lower(), f'"{leaf}"', f"'{leaf}'"]
    full = [f for f, t in blob.items() if col.lower() in t]
    if full:
        return full
    # a column is also read when its group-level name is built dynamically; match leaf only if the group name is in the same file
    return [f for f, t in blob.items() if (f'"{leaf}"' in t or f"'{leaf}'" in t) and group.lower() in t and len(leaf) > 3]


def main():
    base = X._a6_dir()
    live, research = sources()
    rows, tables = [], {}
    for f in sorted(base.glob("*__working_usable.parquet")):
        name = f.name.replace("__working_usable.parquet", "")
        t = pd.read_parquet(f)
        s26 = t[pd.to_numeric(t.get("season", t.get("_season")), errors="coerce") == 2026] if ("season" in t or "_season" in t) else t.iloc[0:0]
        cols = [c for c in t.columns if "__" in c and not META.match(c) and c.split("__", 1)[1] not in IDENT]
        for c in cols:
            n26 = int(s26[c].notna().sum()) if len(s26) else 0
            if n26 == 0:
                continue
            lv, rs = read_in(c, live), read_in(c, research)
            rows.append({"table": name, "column": c, "n_2026": n26, "status": "live" if lv else ("research only" if rs else "unused"), "live_files": lv[:3]})
        tables[name] = {"rows_2026": int(len(s26)), "columns": len(cols)}
    df = pd.DataFrame(rows)
    out = {"created_at": pd.Timestamp.now(tz="UTC").isoformat(), "tables": tables, "counts": df["status"].value_counts().to_dict(), "columns": rows}
    (ROOT / "docs" / "fpds_column_audit.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
    L = ["# FantasyPoints columns with 2026 data: which are read", "", "Generated by `scripts/fpds_column_audit.py`. Names and counts only.", "",
         "| Table | Columns with 2026 data | Read by live projection | Research only | Unused |", "|---|---|---|---|---|"]
    for name, g in df.groupby("table"):
        c = g["status"].value_counts()
        L.append(f"| {name} | {len(g)} | {c.get('live', 0)} | {c.get('research only', 0)} | {c.get('unused', 0)} |")
    L += ["", "## Unused columns", ""]
    for name, g in df[df["status"] == "unused"].groupby("table"):
        L.append(f"- **{name}**: " + ", ".join(sorted(set(g["column"].str.replace("__", ".")))))
    (ROOT / "docs" / "FPDS_COLUMN_AUDIT.md").write_text(chr(10).join(L), encoding="utf-8")
    print(chr(10).join(L[:60])); print(out["counts"])


if __name__ == "__main__":
    main()
