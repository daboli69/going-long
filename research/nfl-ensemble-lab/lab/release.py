    cur = json.loads((HERE / "CURRENT.json").read_text(encoding="utf-8"))
    rel = HERE / cur["release"]
    if not (rel / "lab" / "scheduler.py").is_file():
        raise RuntimeError(f"release folder missing: {rel}")
    os.environ["NFL_LAB_ROOT"] = str(LAB_ROOT)
    os.environ["NFL_LAB_CACHE73_DIR"] = cur["cache_dir"]
    os.environ["NFL_LAB_RELEASE"] = cur["release"]
    os.chdir(rel)
    sys.path.insert(0, str(rel))
    if sys.argv[1:] == ["--check"]:
        import lab, lab.cache73, lab.config
        print(json.dumps({"release": cur["release"], "commit": cur.get("commit"), "lab_package": lab.__file__,
                          "lab_root": str(lab.config.LAB_ROOT), "cache_dir": str(lab.cache73.DIR)}, indent=2))
        return
    stamp = LAB_ROOT / "artifacts" / "scheduler" / "code_version.json"
    stamp.parent.mkdir(parents=True, exist_ok=True)
    stamp.write_text(json.dumps({"release": cur["release"], "commit": cur.get("commit"), "pid": os.getpid(),
                                 "started_utc": datetime.now(timezone.utc).isoformat(timespec="seconds")}), encoding="utf-8")
    sys.argv = ["lab.scheduler", *(sys.argv[1:] or ["tick"])]
    runpy.run_module("lab.scheduler", run_name="__main__", alter_sys=True)


