"""Pinned scheduler releases: the Windows task runs a frozen copy of the lab code, never the dev checkout.

    python -m lab.release release <ref> [--dry-run]   build + test + prewarm (under the scheduler lock) + activate
    python -m lab.release rollback [<label>]           point the launcher back at the previous (or a named) release
    python -m lab.release status                       which code the scheduler runs, every release, the task action
    python -m lab.release task-commands                PowerShell to switch the Windows task to / from the launcher
    (build / test / prewarm / activate / prune run one step at a time)

Layout under LAB_ROOT/releases/ (gitignored):
    <label>/            `git archive` of research/nfl-ensemble-lab at one commit (code read-only) + RELEASE.json
    CURRENT.json        the active release, its cache slot and the previous release (switched atomically)
    history.jsonl       append-only activation / rollback log
    run_tick.pyw        stable launcher the task runs; reads CURRENT.json at the start of every tick
Releases share data/, models/, snapshots/ and artifacts/ through NFL_LAB_ROOT. Each release has its own
Phase 7.3 cache slot (data/cache/phase73_releases/<label>) so development edits never cold its caches.
Switching CURRENT.json never touches the Windows task; changing the task action is a separate, manual step.
"""
